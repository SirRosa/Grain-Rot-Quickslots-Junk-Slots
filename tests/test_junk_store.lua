local M=assert(loadfile("ue4ss/Mods/GrainRotQuickJunk/Scripts/junk_store.lua"))()
local bank=M.new(10)
assert(bank.capacity==10 and bank:count()==0 and bank.selected==1)
assert(bank:cycle(-1) and bank.selected==10)
assert(bank:cycle(1) and bank.selected==1)
assert(not bank:select(11))
local a={}
local tx,err=bank:beginStore("actor/1",a)
assert(tx and tx.slot==1 and not err)
assert(not bank:beginStore("actor/2",{}),"only one pending transaction")
local ok,reason=bank:confirm(tx,false)
assert(not ok and reason=="unverified" and bank:count()==0)
tx=assert(bank:beginStore("actor/1",a))
assert(bank:confirm(tx,true) and bank:count()==1)
assert(not bank:beginStore("actor/1",{}),"duplicate actor identity")
for i=2,10 do
  local token=assert(bank:beginStore("actor/"..i,{}))
  assert(token.slot==i)
  assert(bank:confirm(token,true))
end
assert(bank:count()==10 and not bank:beginStore("actor/11",{}),"capacity must be 10")
assert(bank:select(1))
local out=assert(bank:beginWithdraw())
assert(out.actor==a)
assert(not bank:beginWithdraw(2),"transaction cannot overlap")
ok,reason=bank:confirm(out,false)
assert(not ok and reason=="unverified")
assert(bank:count()==10 and bank:find("actor/1")==1,"failed retrieve must keep ownership")
out=assert(bank:beginWithdraw(1))
assert(bank:confirm(out,true))
assert(bank:count()==9 and bank.slots[1]==nil)
local again=assert(bank:beginStore("actor/1",a))
assert(again.slot==1)
assert(bank:cancel(again))
assert(bank.slots[1]==nil)
assert(not bank:confirm(again,true),"cancelled transaction cannot commit")
local second=assert(bank:beginStore("actor/1",a))
assert(bank:confirm(second,true) and bank.slots[1].actor==a)
local errorTx, why=bank:beginStore("",{})
assert(errorTx==nil and why=="invalid_item")
io.write("PASS: 10 distinct slots, wraparound, capacity, transactional commit/rollback and anti-duplication\n")
